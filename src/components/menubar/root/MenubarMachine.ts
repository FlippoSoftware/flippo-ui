import { Store, untracked } from '@flippo-software/store';

import { getStyleHookProps } from '~@attributes/getStyleHookProps';
import { CompositeRootMachine } from '~@components/composite/root/CompositeRootMachine';
import { acquireScrollLock } from '~@dom/scrollLock';
import { Connectable } from '~@lib/Connectable';
import { OptionsStore } from '~@lib/OptionsStore';
import { FloatingNodeRegistration } from '~@packages/floating-ui/FloatingNodeRegistration';
import { FloatingTreeStore } from '~@packages/floating-ui/FloatingTreeStore';
import { Effect } from '~@packages/floating-ui/utils/Effect';
import { mergeProps } from '~@props/mergeProps';

import type { MenuOpenEventDetails } from '~@components/menu/positioner/MenuPositionerMachine';
import type { MenubarParentContext, MenuOrientation } from '~@components/menu/store/MenuStore';
import type { MutableRef, TextDirection } from '~@lib/types';
import type { Props } from '~@props/mergeProps';

import { menubarStateAttributesMapping } from './menubarStateAttributesMapping';

export type MenubarState = {
    orientation: MenuOrientation;
    modal: boolean;
    hasSubmenuOpen: boolean;
};

export type MenubarOptions = {
    /**
     * @default 'horizontal'
     */
    orientation?: MenuOrientation | undefined;
    /**
     * @default true
     */
    loopFocus?: boolean | undefined;
    /**
     * @default true
     */
    modal?: boolean | undefined;
    /**
     * @default false
     */
    disabled?: boolean | undefined;
};

export type MenubarSetup = {
    /**
     * ID of the menubar (generated by the adapter when not provided).
     */
    id: string;
    /**
     * Generated ID of the menubar's floating tree node.
     */
    nodeId: string;
    /**
     * @default 'ltr'
     */
    direction?: TextDirection | undefined;
};

type MenubarInternalState = {
    contentElement: HTMLElement | null;
    hasSubmenuOpen: boolean;
    openMethod: 'mouse' | 'touch' | 'keyboard' | null;
};

/**
 * State machine of `Menubar`: a composite of menu triggers sharing one floating tree; it tracks
 * whether a menu is open (then hovering other triggers opens their menus) and locks scrolling when modal.
 *
 * `context` is passed to the menus as their `{ type: 'menubar' }` parent.
 */
export class MenubarMachine extends Connectable {
    readonly store = new Store<MenubarInternalState>({ contentElement: null, hasSubmenuOpen: false, openMethod: null });

    readonly tree = new FloatingTreeStore();

    readonly composite: CompositeRootMachine;

    readonly allowMouseUpTriggerRef: MutableRef<boolean> = { current: false };

    /**
     * The options, in a store: computed values and effects reading them follow their changes, key by key.
     */
    private readonly optionsStore = new OptionsStore<MenubarOptions>({} as MenubarOptions);

    private get options(): MenubarOptions {
        return this.optionsStore.state;
    }

    private set options(options: MenubarOptions) {
        this.optionsStore.setState(options);
    }

    private readonly setup: MenubarSetup;

    private readonly node: FloatingNodeRegistration;

    private readonly scrollLock = new Effect(() => {
        const { hasSubmenuOpen, openMethod, contentElement } = this.store.state;
        if (!(this.modal && hasSubmenuOpen && openMethod !== 'touch')) {
            return;
        }
        return acquireScrollLock(contentElement);
    });

    constructor(options: MenubarOptions, setup: MenubarSetup) {
        super();
        this.options = options;
        this.setup = setup;
        this.node = new FloatingNodeRegistration(this.tree, setup.nodeId, null);
        this.composite = new CompositeRootMachine(this.getCompositeOptions());
    }

    protected override onConnect() {
        this.connectChild(this.node);
        this.connectChild(this.composite);
        this.tree.events.on('menuopenchange', this.onSubmenuOpenChange);
        this.addCleanup(() => this.tree.events.off('menuopenchange', this.onSubmenuOpenChange));
        this.addCleanup(this.store.subscribe(() => this.sync()));
        this.sync();
    }

    setOptions(options: MenubarOptions) {
        // What the machine reads while applying its options is not a dependency of the caller (e.g. an effect).
        untracked(() => {
            this.options = options;
            this.composite.setOptions(this.getCompositeOptions());
        });
    }

    /**
     * Applies the options' side effects after a commit.
     */
    afterCommit() {
        this.sync();
    }

    private get modal() {
        return this.options.modal ?? true;
    }

    /**
     * The parent context for the menubar's menus (pass it as `{ type: 'menubar', context }`).
     * One object whose fields always read the current menubar state.
     */
    readonly context: MenubarParentContext = (() => {
        const machine = this;
        return {
            get disabled() {
                return machine.options.disabled ?? false;
            },
            get rootId() {
                return machine.setup.id;
            },
            get allowMouseUpTriggerRef() {
                return machine.allowMouseUpTriggerRef;
            },
            get modal() {
                return machine.modal;
            },
            get orientation() {
                return machine.options.orientation ?? 'horizontal';
            },
            get hasSubmenuOpen() {
                return machine.store.state.hasSubmenuOpen;
            },
            get contentElement() {
                return machine.store.state.contentElement;
            },
            get tree() {
                return machine.tree;
            },
            get nodeId() {
                return machine.setup.nodeId;
            }
        };
    })();

    setElement = (element: HTMLElement | null) => {
        this.store.set('contentElement', element);
        this.composite.setRoot(element);
    };

    getState(): MenubarState {
        return {
            orientation: this.options.orientation ?? 'horizontal',
            modal: this.modal,
            hasSubmenuOpen: this.store.state.hasSubmenuOpen
        };
    }

    static attrs(state: MenubarState) {
        return getStyleHookProps(state, menubarStateAttributesMapping);
    }

    getMenubarProps(elementProps: Props = {}): Props {
        return mergeProps(
            this.composite.getRootProps(),
            { role: 'menubar', id: this.setup.id },
            {
                onPointerDown: (event: PointerEvent) => {
                    this.store.set('openMethod', event.pointerType === 'touch' ? 'touch' : 'mouse');
                },
                onKeyDown: () => {
                    this.store.set('openMethod', 'keyboard');
                }
            },
            elementProps
        );
    }

    protected override onDisconnect() {
        this.scrollLock.destroy();
    }

    private getCompositeOptions() {
        return {
            orientation: this.options.orientation ?? 'horizontal',
            loopFocus: this.options.loopFocus ?? true,
            highlightItemOnHover: this.store.state.hasSubmenuOpen,
            direction: this.setup.direction ?? 'ltr'
        };
    }

    private sync() {
        if (!this.connected) {
            return;
        }
        if (!this.store.state.hasSubmenuOpen && this.store.state.openMethod !== null) {
            this.store.set('openMethod', null);
        }
        this.composite.setOptions(this.getCompositeOptions());
        this.scrollLock.sync([this.modal, this.store.state.hasSubmenuOpen, this.store.state.openMethod, this.store.state.contentElement]);
    }

    private readonly onSubmenuOpenChange = (details: MenuOpenEventDetails) => {
        if (!details.nodeId || details.parentNodeId !== this.setup.nodeId) {
            return;
        }
        if (details.open) {
            this.store.set('hasSubmenuOpen', true);
        } else if (details.reason !== 'sibling-open' && details.reason !== 'list-navigation') {
            this.store.set('hasSubmenuOpen', false);
        }
    };
}
