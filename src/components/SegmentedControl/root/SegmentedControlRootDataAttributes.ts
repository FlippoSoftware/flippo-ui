export enum SegmentedControlRootDataAttributes {
    /**
     * Present when the segmented control is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present when the segmented control is readonly.
     */
    readonly = 'data-readonly',
    /**
     * Indicates the orientation of the segmented control.
     * @type {'horizontal' | 'vertical'}
     */
    orientation = 'data-orientation'
}
