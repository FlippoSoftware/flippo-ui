export enum RadioCardRootDataAttributes {
    /**
     * Present when the radio card is checked.
     */
    checked = 'data-checked',
    /**
     * Present when the radio card is not checked.
     */
    unchecked = 'data-unchecked',
    /**
     * Present when the radio card is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present when the radio card is readonly.
     */
    readonly = 'data-readonly',
    /**
     * Present when the radio card is required.
     */
    required = 'data-required'
}
