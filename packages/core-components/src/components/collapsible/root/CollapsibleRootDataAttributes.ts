export enum CollapsibleRootDataAttributes {
    /**
     * Present when the collapsible is open.
     */
    open = 'data-open',
    /**
     * Present when the collapsible is closed.
     */
    closed = 'data-closed',
    /**
     * Present when the collapsible is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present while the panel is animating in.
     */
    startingStyle = 'data-starting-style',
    /**
     * Present while the panel is animating out.
     */
    endingStyle = 'data-ending-style'
}
