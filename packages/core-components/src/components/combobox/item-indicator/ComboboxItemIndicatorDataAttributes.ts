export enum ComboboxItemIndicatorDataAttributes {
    /**
     * Present when the item is selected.
     */
    selected = 'data-selected',
    /**
     * Present while the selection indicator is animating in.
     */
    startingStyle = 'data-starting-style',
    /**
     * Present while the selection indicator is animating out.
     */
    endingStyle = 'data-ending-style'
}
