export enum ComboboxClearDataAttributes {
    /**
     * Present when the combobox popup is open.
     */
    popupOpen = 'data-popup-open',
    /**
     * Present when the clear button is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present while the clear button is animating in.
     */
    startingStyle = 'data-starting-style',
    /**
     * Present while the clear button is animating out.
     */
    endingStyle = 'data-ending-style'
}
