export enum CheckboxIndicatorDataAttributes {
    /**
     * Present when the checkbox is checked.
     */
    checked = 'data-checked',
    /**
     * Present when the checkbox is not checked.
     */
    unchecked = 'data-unchecked',
    /**
     * Present when the checkbox is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present when the checkbox is readonly.
     */
    readonly = 'data-readonly',
    /**
     * Present when the checkbox is required.
     */
    required = 'data-required',
    /**
     * Present when the checkbox is in valid state (inside a field).
     */
    valid = 'data-valid',
    /**
     * Present when the checkbox is in invalid state (inside a field).
     */
    invalid = 'data-invalid',
    /**
     * Present when the checkbox has been touched (inside a field).
     */
    touched = 'data-touched',
    /**
     * Present when the checkbox's value has changed (inside a field).
     */
    dirty = 'data-dirty',
    /**
     * Present when the checkbox is checked (inside a field).
     */
    filled = 'data-filled',
    /**
     * Present when the checkbox is focused (inside a field).
     */
    focused = 'data-focused',
    /**
     * Present when the checkbox indicator is animating in.
     */
    startingStyle = 'data-starting-style',
    /**
     * Present when the checkbox indicator is animating out.
     */
    endingStyle = 'data-ending-style'
}
