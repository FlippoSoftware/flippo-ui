export enum CheckboxCardRootDataAttributes {
    /**
     * Present when the checkbox card is checked.
     */
    checked = 'data-checked',
    /**
     * Present when the checkbox card is not checked.
     */
    unchecked = 'data-unchecked',
    /**
     * Present when the checkbox card is in an indeterminate state.
     */
    indeterminate = 'data-indeterminate',
    /**
     * Present when the checkbox card is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present when the checkbox card is required.
     */
    required = 'data-required'
}
