export enum DrawerPopupCssVars {
    /**
     * The number of drawers open inside this one.
     */
    nestedDrawers = '--nested-drawers',
    /**
     * The distance the popup has been dragged, in pixels.
     */
    dragOffset = '--drag-offset',
    /**
     * The distance the popup has been swiped, in pixels, while it is swiped.
     */
    swipeMovement = '--swipe-movement',
    /**
     * The offset of the active snap point, in pixels.
     */
    snapPointTransform = '--snap-point-transform',
    /**
     * The offset of the largest snap point, in pixels.
     */
    snapPointMax = '--snap-point-max',
    /**
     * The index of the active snap point.
     */
    snapPointIndex = '--snap-point-index'
}
