export enum NumberFieldDecrementDataAttributes {
    /**
     * Present while scrubbing.
     */
    scrubbing = 'data-scrubbing',
    /**
     * Present when the number field is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present when the number field is readonly.
     */
    readonly = 'data-readonly',
    /**
     * Present when the number field is required.
     */
    required = 'data-required',
    /**
     * Present when the number field is in valid state (inside a field).
     */
    valid = 'data-valid',
    /**
     * Present when the number field is in invalid state (inside a field).
     */
    invalid = 'data-invalid',
    /**
     * Present when the number field has been touched (inside a field).
     */
    touched = 'data-touched',
    /**
     * Present when the number field's value has changed (inside a field).
     */
    dirty = 'data-dirty',
    /**
     * Present when the number field is filled (inside a field).
     */
    filled = 'data-filled',
    /**
     * Present when the number field is focused (inside a field).
     */
    focused = 'data-focused'
}
