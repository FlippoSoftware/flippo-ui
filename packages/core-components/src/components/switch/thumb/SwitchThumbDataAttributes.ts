export enum SwitchThumbDataAttributes {
    /**
     * Present when the switch is checked.
     */
    checked = 'data-checked',
    /**
     * Present when the switch is not checked.
     */
    unchecked = 'data-unchecked',
    /**
     * Present when the switch is disabled.
     */
    disabled = 'data-disabled',
    /**
     * Present when the switch is readonly.
     */
    readonly = 'data-readonly',
    /**
     * Present when the switch is required.
     */
    required = 'data-required',
    /**
     * Present when the switch is in valid state (inside a field).
     */
    valid = 'data-valid',
    /**
     * Present when the switch is in invalid state (inside a field).
     */
    invalid = 'data-invalid',
    /**
     * Present when the switch has been touched (inside a field).
     */
    touched = 'data-touched',
    /**
     * Present when the switch's value has changed (inside a field).
     */
    dirty = 'data-dirty',
    /**
     * Present when the switch is active (inside a field).
     */
    filled = 'data-filled',
    /**
     * Present when the switch is focused (inside a field).
     */
    focused = 'data-focused'
}
