/**
 * Compiles the stylesheets to `dist/css`:
 * - `tokens.css`, `reset.css`, `shared.css`, `base.css` (the three together), `fonts.css`;
 * - `components/<name>.css` for every component with a stylesheet;
 * - `index.css`: fonts, base and every component.
 */
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from 'sass';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'dist', 'css');
const componentsDir = join(root, 'src', 'components');

export function componentStylesheets(): string[] {
    return readdirSync(componentsDir)
        .filter((name) => existsSync(join(componentsDir, name, `${name}.scss`)))
        .sort();
}

function write(file: string, css: string) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, `${css}\n`);
}

function build() {
    rmSync(outDir, { recursive: true, force: true });

    for (const name of ['tokens', 'reset', 'shared', 'base', 'fonts']) {
        write(join(outDir, `${name}.css`), compile(join(root, 'src', 'styles', `${name}.scss`)).css);
    }

    const components = componentStylesheets();
    for (const name of components) {
        write(join(outDir, 'components', `${name}.css`), compile(join(componentsDir, name, `${name}.scss`)).css);
    }

    // `index.scss` is generated so it never misses a component; `@use` writes every module once.
    const indexSource = join(root, 'src', 'styles', 'index.scss');
    const uses = ['fonts', 'base', ...components.map((name) => `../components/${name}/${name}`)];
    writeFileSync(
        indexSource,
        `// Generated by scripts/build-css.ts: fonts, tokens, reset, shared classes and every component.\n${uses
            .map((path) => `@use '${path}';`)
            .join('\n')}\n`
    );
    write(join(outDir, 'index.css'), compile(indexSource).css);

    console.log(`Built ${components.length} component stylesheets into ${relative(root, outDir)}.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    build();
}
